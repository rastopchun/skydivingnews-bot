def trim_body(body: str, max_chars: int = BODY_MAX_CHARS) -> str:
    body = body.split("\n\n")[0]
    body = re.sub(r"\s*\n\s*", " ", body).strip()
    body = re.sub(r"\s{2,}", " ", body)

    if len(body) <= max_chars:
        return body

    cut = body[:max_chars]
    end = max(cut.rfind("."), cut.rfind("!"), cut.rfind("?"), cut.rfind("»"))
    if end >= 80:
        return cut[:end + 1].strip()
    return cut.rstrip(" ,;:—-") + "…"


def quality_reject(headline: str, body: str) -> str | None:
    text = f"{headline} {body}".lower()

    if len(headline) > HEADLINE_MAX_CHARS:
        return "заголовок слишком длинный"

    if len(body) > BODY_MAX_CHARS:
        return "тело слишком длинное"

    if has_any_pattern(text, BANNED_PATTERNS):
        return "запрещённая лексика"

    if has_any_pattern(text, BAD_STYLE_PATTERNS):
        return "новостные штампы вместо сухого абсурда"

    if has_any_pattern(text, POLITICS_MILITARY_OUT):
        return "военно-политическая тема в тексте (юр. риск)"

    if not has_any_fragment(text, SKY_ANCHORS):
        return "нет настоящего парашютного якоря"

    if count_fragments(text, SKY_TERMS) > 4:
        return "перегруз парашютными терминами"

    if text.count(",") > 6:
        return "перегруженное предложение"

    persons = detect_persons(text)
    if len(persons) > 1:
        return "больше одного известного человека"

    recent_persons = set(load_recent_persons())
    if set(persons) & recent_persons:
        return "персона недавно уже была"

    return None


def parse_news(raw: str) -> dict:
    try:
        data = json.loads(raw)
    except json.JSONDecodeError:
        # На всякий случай вынимаем первый JSON-объект, если модель добавила мусор.
        m = re.search(r"\{.*\}", raw, flags=re.S)
        if not m:
            raise
        data = json.loads(m.group(0))

    if not isinstance(data, dict):
        raise RuntimeError("ответ модели не JSON-объект")

    headline = str(data.get("headline", "")).strip()
    body = str(data.get("body", "")).strip()

    if not headline or not body:
        raise RuntimeError(f"пустой ответ модели: {raw[:200]}")

    return {"headline": headline, "body": body}


def fetch_source_headlines(url: str) -> list:
    """Скачивает RSS-ленту и вытаскивает заголовки новостей (item titles)."""
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "skydive-news-bot/2.0"})
        with urllib.request.urlopen(req, timeout=20) as r:
            xml = r.read().decode("utf-8", "replace")
    except Exception:
        return []
    raw = re.findall(r"<title>\s*(?:<!\[CDATA\[)?(.*?)(?:\]\]>)?\s*</title>", xml, re.S)
    out = []
    for t in raw:
        t = re.sub(r"<[^>]+>", " ", t)
        for a, b in [("&amp;", "&"), ("&quot;", '"'), ("&#39;", "'"), ("&apos;", "'"),
                     ("&laquo;", "«"), ("&raquo;", "»"), ("&mdash;", "—"), ("&nbsp;", " ")]:
            t = t.replace(a, b)
        t = " ".join(t.split()).strip()
        if t:
            out.append(t)
    # первый <title> обычно — название самой ленты, отбрасываем
    return out[1:] if len(out) > 1 else out


def pick_source_headline() -> str | None:
    """Берёт свежий, не трагичный и не повторявшийся реальный заголовок."""
    recent = read_json_list(SOURCE_STATE)
    feeds = list(NEWS_FEEDS)
    random.shuffle(feeds)
    for url in feeds:
        titles = fetch_source_headlines(url)
        pool = [
            t for t in titles
            if 15 <= len(t) <= 120
            and not has_any_pattern(t, SENSITIVE_WORDS)
            and t not in recent
        ]
        if pool:
            choice = random.choice(pool[:40])
            recent.append(choice)
            write_json(SOURCE_STATE, recent[-SOURCE_COOLDOWN:])
            return choice
    return None


