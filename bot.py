def html_escape(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def format_message(news: dict) -> str:
    headline = html_escape(news["headline"])
    body = html_escape(news["body"])
    parts = [f"<b>{headline}</b>", "", body]
    if FOOTER:
        parts += ["", FOOTER]
    return "\n".join(parts)


def parse_channels(raw: str) -> list:
    """CHANNEL_ID может быть списком через запятую: '@one, @two' → ['@one','@two']."""
    return [c.strip() for c in raw.split(",") if c.strip()]


def tg_send_message(text: str, chat_id: str) -> dict:
    payload = json.dumps({
        "chat_id": chat_id,
        "text": text,
        "parse_mode": "HTML",
        "disable_web_page_preview": True,
    }).encode("utf-8")

    req = urllib.request.Request(
        TG_API_BASE + "/sendMessage",
        data=payload,
        headers={"Content-Type": "application/json", "User-Agent": "skydive-news-bot/2.0"},
    )

    try:
        with urllib.request.urlopen(req, timeout=45) as resp:
            return json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        body = e.read().decode("utf-8", "replace")
        try:
            return json.loads(body)
        except Exception:
            return {"ok": False, "description": f"HTTP {e.code}: {body}"}


